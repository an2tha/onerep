// Run with Bun from the repository root when editing the public REST contract.
import { API_ROUTES } from "../convex/api/rest";
import { findTool } from "../convex/mcp/tools";
import { readFileSync, writeFileSync } from "node:fs";

type Schema = {
  type?: string | string[];
  enum?: unknown[];
  properties?: Record<string, Schema>;
  items?: Schema;
  required?: string[];
};
function typeOf(schema: Schema): string {
  if (schema.enum) return schema.enum.map((v) => JSON.stringify(v)).join(" | ");
  if (Array.isArray(schema.type))
    return schema.type.map((type) => typeOf({ ...schema, type })).join(" | ");
  switch (schema.type) {
    case "integer":
    case "number":
      return "number";
    case "string":
    case "boolean":
    case "null":
      return schema.type;
    case "array":
      return `Array<${typeOf(schema.items ?? {})}>`;
    case "object": {
      const fields = Object.entries(schema.properties ?? {}).map(
        ([key, value]) =>
          `${key}${schema.required?.includes(key) ? "" : "?"}: ${typeOf(value)}`,
      );
      return fields.length
        ? `{ ${fields.join("; ")} }`
        : "Record<string, never>";
    }
    default:
      return "unknown";
  }
}

const routes = API_ROUTES.map(({operation, method, path, scope, summary}) => {
  const schema = findTool(operation)?.inputSchema;
  const required = new Set(schema?.required);
  for (const match of path.matchAll(/:(\w+)/g)) required.add(match[1]);
  const input = typeOf({type: "object", properties: schema?.properties ?? {}, required: [...required]} as Schema);
  return {operation, method, path, scope, summary, input};
});
const inputs = routes.map(({operation, input}) => `  ${operation}: ${input};`);
const output =
  "// Generated by scripts/generate-sdk.ts\nexport const operations = " +
  JSON.stringify(routes, null, 2) +
  " as const;\n\nexport interface Inputs {\n" +
  inputs.join("\n") +
  "\n}\n";
const target = new URL("../packages/sdk/src/operations.ts", import.meta.url);
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== output)
    throw new Error("Run bun scripts/generate-sdk.ts");
} else writeFileSync(target, output);
