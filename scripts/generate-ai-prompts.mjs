import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourceDir = resolve(root, "convex/ai/prompts");
const outputPath = resolve(root, "convex/ai/prompts.generated.ts");

function parsePromptYaml(source, filename) {
  const lines = source.replaceAll("\r\n", "\n").split("\n");
  const idLine = lines.find((line) => line.startsWith("id:"));
  const id = idLine?.slice(3).trim();
  if (!id || !/^[a-z][a-z0-9_]*$/.test(id)) {
    throw new Error(`${filename}: missing or invalid id`);
  }

  const systemIndex = lines.findIndex((line) =>
    /^system:\s*\|-?\s*$/.test(line),
  );
  if (systemIndex < 0) throw new Error(`${filename}: missing system block`);
  const body = [];
  for (const line of lines.slice(systemIndex + 1)) {
    if (line && !line.startsWith("  ")) break;
    body.push(line.startsWith("  ") ? line.slice(2) : line);
  }
  const system = body.join("\n").trim();
  if (!system) throw new Error(`${filename}: system prompt is empty`);
  return { id, system };
}

const filenames = (await readdir(sourceDir))
  .filter((name) => name.endsWith(".yaml"))
  .sort();
if (filenames.length === 0) throw new Error("No AI prompt YAML files found");
const prompts = [];
const seen = new Set();
for (const filename of filenames) {
  const parsed = parsePromptYaml(
    await readFile(resolve(sourceDir, filename), "utf8"),
    filename,
  );
  if (seen.has(parsed.id)) throw new Error(`Duplicate prompt id: ${parsed.id}`);
  seen.add(parsed.id);
  prompts.push(parsed);
}

const entries = prompts
  .map(
    ({ id, system }) => `  ${JSON.stringify(id)}: ${JSON.stringify(system)},`,
  )
  .join("\n");
const output = `// Generated by scripts/generate-ai-prompts.mjs. Do not edit directly.\n// Source of truth: convex/ai/prompts/*.yaml\n\nexport const promptTemplates = {\n${entries}\n} as const;\n\nexport type PromptId = keyof typeof promptTemplates;\n\nexport function renderSystemPrompt(\n  id: PromptId,\n  variables: Record<string, string | number> = {},\n) {\n  return promptTemplates[id].replace(\n    /\\{\\{\\s*([a-zA-Z0-9_]+)\\s*\\}\\}/g,\n    (_match, key: string) => {\n      const value = variables[key];\n      if (value === undefined) {\n        throw new Error("Missing prompt variable " + key + " for " + id);\n      }\n      return String(value);\n    },\n  );\n}\n`;

if (process.argv.includes("--check")) {
  const current = await readFile(outputPath, "utf8").catch(() => "");
  if (current !== output) {
    throw new Error("AI prompt bundle is stale. Run: bun run prompts:generate");
  }
} else {
  await writeFile(outputPath, output);
}
